def ceremony_key_commitment(key: bytes) -> str:
    """Commit to evaluator key bytes without making those bytes public."""
    if not isinstance(key, bytes) or len(key) != 32:
        raise ValueError("ceremony key must be exactly 32 bytes")
    digest = hashlib.sha256(BENCHMARK_CEREMONY_KEY_COMMITMENT_DOMAIN + key).hexdigest()
    return "sha256:" + digest


def ceremony_id_from_entropy(entropy: bytes) -> str:
    """Encode one independently minted 128-bit ceremony identifier."""
    if not isinstance(entropy, bytes) or len(entropy) != 16:
        raise ValueError("ceremony identifier entropy must be exactly 16 bytes")
    return "afc1_" + base64.b32encode(entropy).decode("ascii").rstrip("=").lower()


def _validate_ceremony_created_at(value: object) -> str:
    if not isinstance(value, str) or _CEREMONY_CREATED_AT.fullmatch(value) is None:
        raise ValueError("ceremony created_at must be canonical UTC with six fractional digits")
    try:
        parsed = datetime.strptime(value, "%Y-%m-%dT%H:%M:%S.%fZ")
    except ValueError as exc:
        raise ValueError("ceremony created_at is not a real UTC timestamp") from exc
    if parsed.strftime("%Y-%m-%dT%H:%M:%S.%fZ") != value:
        raise ValueError("ceremony created_at is not canonical")
    return value


