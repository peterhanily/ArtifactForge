def validate_benchmark_scenario_count(value: object) -> int:
    """Return one bounded suite population before generation can touch the filesystem."""
    if isinstance(value, bool) or not isinstance(value, int):
        raise ValueError("benchmark suite size must be an integer")
    if value < 1 or value > BENCHMARK_MAX_SCENARIOS:
        raise ValueError(f"benchmark suite size must be between 1 and {BENCHMARK_MAX_SCENARIOS}")
    return value


def validate_benchmark_v3_scenario_count(value: object) -> int:
    """Require the balanced population covered by v3's predeclared sparse-power contract."""
    count = validate_benchmark_scenario_count(value)
    if count < BENCHMARK_V3_MIN_SCENARIOS or count % 2:
        raise ValueError(
            "benchmark v3 ceremony size must be an even integer between "
            f"{BENCHMARK_V3_MIN_SCENARIOS} and {BENCHMARK_MAX_SCENARIOS}"
        )
    return count


def benchmark_public_file_count(scenario_count: object) -> int:
    """Exact current public-export file count under the alternating family schedule."""
    count = validate_benchmark_scenario_count(scenario_count)
    per_family = dict(BENCHMARK_ARTIFACT_FILES_PER_SCENE)
    windows = (count + 1) // 2
    macos = count // 2
    return 1 + windows * per_family["windows"] + macos * per_family["macos"]


def benchmark_question_prompt(rule: str, selector: dict) -> str:
    """Return the one canonical public prompt for a closed benchmark rule.

    Prompts are executable protocol, not editorial prose: changing one can create a new
    shortcut or make two otherwise identical suites incomparable.  Keeping their rendering
    beside the public-schema constants lets generation and loading enforce the same bytes.
    """
    if rule == WINDOWS_AMCACHE_RULE:
        if set(selector) != {"lower_case_long_path"}:
            raise ValueError("Windows benchmark selector has a non-canonical shape")
        path = selector["lower_case_long_path"]
        return (
            "In Amcache InventoryApplicationFile, select the row whose "
            f"LowerCaseLongPath is {path!r}. Its FileId records a SHA1. Hash the "
            "resident PE candidates and give the SHA256 of the one whose bytes agree."
        )
    if rule == MACOS_QUARANTINE_RULE:
        if set(selector) != {"xattr_relative_path"}:
            raise ValueError("macOS benchmark selector has a non-canonical shape")
        path = selector["xattr_relative_path"]
        return (
            f"Read the serialized com.apple.quarantine xattr at {path!r}. Join its "
            "event UUID to QuarantineEventsV2 and give that event's data URL."
        )
    raise ValueError(f"unsupported benchmark question rule: {rule!r}")


