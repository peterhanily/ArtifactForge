"""Keyed suite derivation — how a deterministic generator can still have unguessable answers.

Determinism and unguessability look like opposites. Under one declared protocol implementation
and ABI, a batch must regenerate byte-identically, which means every answer is a pure function
of something; and the generator is open source, which means anyone can compute that function.
Cross-version identity requires an explicit compatibility contract. The previous design
resolved this by accident and badly: `scenario_id` was both the label handed to the solver
*and* the seed the answers were derived from, so a solver that opened no file at all scored
100%.

The resolution is a secret, introduced in exactly one place. Every derivation hangs off a
32-byte **suite key**. The public identifier is an HMAC of the key and the index, so it is
stable, deterministic and reproducible *given the key* — and reveals nothing without it.
Domain-separated leaf keys keep the public identifier, the content seed, and each variable
selection independent, so recovering one tells you nothing about the others.

Benchmark v2 has three historical suite labels.  They remain parseable so old fixtures and
diagnostics do not acquire new semantics by being loaded with newer code, but every v2 suite
is permanently local and non-reportable:

  **dev** — built with `PUBLIC_DEV_KEY`, which is printed below on purpose. Anyone can
  regenerate it, inspect it, and cheat on it. That is what makes it useful for development
  and useless as a score. `bench grade` refuses to report a bare accuracy for a dev suite.

  **hold-out** — the historical label for a caller-keyed local suite.  A secret key is useful
  diagnostic hygiene, but v2 records no evaluator-created freshness ceremony and can never
  support a reportable result.

  **scorecard-measurement** — built with a separately domain-separated public key. It exists
  only so the committed project scorecard can be regenerated byte-for-byte. Like a dev suite,
  it is deliberately reproducible and therefore never reportable as a benchmark score.

Benchmark v3 is deliberately separate.  Its evaluator-ceremony constructor mints key material
internally, binds an exact origin/reportability block into ``suite_id``, and retains a private
ceremony record.  That is local self-attestation only: external isolation, independence and
one-shot evaluation still require evidence outside this process.
"""

