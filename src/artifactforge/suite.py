_SEP = b"\x1f"


class _PublicJSONError(ValueError):
    pass


def _public_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise _PublicJSONError(f"duplicate object member: {key!r}")
        result[key] = value
    return result


def _validate_public_json(value: object, where: str = "$") -> None:
    if value is None or isinstance(value, bool):
        return
    if isinstance(value, str):
        if unicodedata.normalize("NFC", value) != value:
            raise _PublicJSONError(f"{where} is not Unicode NFC")
        value.encode("utf-8", errors="strict")
        return
    if isinstance(value, int):
        return
    if isinstance(value, list):
        for index, item in enumerate(value):
            _validate_public_json(item, f"{where}[{index}]")
        return
    if isinstance(value, dict):
        for key, item in value.items():
            if not isinstance(key, str):
                raise _PublicJSONError(f"{where} has a non-string member name")
            _validate_public_json(key, f"{where} member name")
            _validate_public_json(item, f"{where}.{key}")
        return
    raise _PublicJSONError(f"{where} has unsupported JSON type {type(value).__name__}")


def _load_public_json(data: bytes) -> object:
    if data.startswith(b"\xef\xbb\xbf"):
        raise _PublicJSONError("UTF-8 BOM is forbidden")
    try:
        text = data.decode("utf-8", errors="strict")
        value = json.loads(
            text,
            object_pairs_hook=_public_object,
            parse_float=lambda token: (_ for _ in ()).throw(
                _PublicJSONError(f"floating-point JSON number is forbidden: {token}")
            ),
            parse_constant=lambda token: (_ for _ in ()).throw(
                _PublicJSONError(f"non-finite JSON number is forbidden: {token}")
            ),
        )
    except _PublicJSONError:
        raise
    except (UnicodeError, json.JSONDecodeError, RecursionError, ValueError) as exc:
        raise _PublicJSONError(f"invalid JSON: {exc}") from exc
    try:
        _validate_public_json(value)
    except _PublicJSONError:
        raise
    except (UnicodeError, RecursionError) as exc:
        raise _PublicJSONError(f"invalid JSON value: {exc}") from exc
    return value


def _canonical_public_json(value: object) -> bytes:
    _validate_public_json(value)
    try:
        rendered = json.dumps(
            value,
            allow_nan=False,
            ensure_ascii=False,
            separators=(",", ":"),
            sort_keys=True,
        )
    except (TypeError, ValueError, RecursionError) as exc:
        raise _PublicJSONError(f"cannot encode canonical public JSON: {exc}") from exc
    return (rendered + "\n").encode("utf-8", errors="strict")


def _load_canonical_public_json(data: bytes) -> object:
    value = _load_public_json(data)
    if data != _canonical_public_json(value):
        raise _PublicJSONError("public.json is not canonical sorted compact UTF-8 JSON")
    return value


def _private_stage_directory(parent_fd: int, parent: Path, final_name: str) -> Path:
    """Create an unpublished same-filesystem directory without touching global temp policy."""
    for _attempt in range(32):
        candidate_name = f".{final_name}.stage-{secrets.token_hex(8)}"
        try:
            os.mkdir(candidate_name, mode=0o700, dir_fd=parent_fd)
            os.chmod(
                candidate_name,
                0o700,
                dir_fd=parent_fd,
                follow_symlinks=False,
            )
            return parent / candidate_name
        except FileExistsError:
            continue
        except (NotImplementedError, OSError) as exc:
            raise ValueError(
                f"cannot reserve a private staging directory below {parent}: {exc}"
            ) from exc
    raise ValueError(f"cannot reserve a private staging directory below {parent}")


def _directory_path_matches_descriptor(path: Path, descriptor: int) -> bool:
    try:
        path_state = path.lstat()
        opened = os.fstat(descriptor)
    except OSError:
        return False
    return (
        path_state.st_dev,
        path_state.st_ino,
    ) == (opened.st_dev, opened.st_ino)


def _domain_mac(key: bytes, domain: bytes, *parts: str) -> bytes:
    """HMAC-SHA256 over domain-separated parts. Unit separators make the parts unambiguous,
    so ("ab", "c") and ("a", "bc") cannot derive the same value."""
    msg = domain + _SEP + _SEP.join(p.encode() for p in parts)
    return hmac.new(key, msg, hashlib.sha256).digest()


def _mac(key: bytes, *parts: str) -> bytes:
    """Derive benchmark-protocol identities in the current benchmark domain."""
    return _domain_mac(key, DOMAIN, *parts)


def scene_value(skey: bytes, *parts: str) -> bytes:
    """Derive scene-local values under the independently frozen scene byte contract."""
    return _domain_mac(skey, SCENE_VALUE_DOMAIN, *parts)


def new_key() -> bytes:
    """Mint a raw local v2 diagnostic key; this is not a v3 freshness ceremony."""
    return secrets.token_bytes(32)


def scorecard_measurement_key() -> bytes:
    """The public deterministic key used only by ``artifactforge scorecard``.

    Domain separation makes accidental reuse of the dev-suite key visible in both code and
    provenance. This key provides reproducibility, not secrecy; a corpus made from it is never
    a hold-out and must never produce a reportable benchmark score.
    """
    return hmac.new(
        SCORECARD_MEASUREMENT_SEED, SCORECARD_MEASUREMENT_KEY_DOMAIN, hashlib.sha256
    ).digest()


def scorecard_measurement_key_id() -> str:
    """A non-key fingerprint suitable for a public scorecard provenance block."""
    return "sha256:" + hashlib.sha256(scorecard_measurement_key()).hexdigest()


def validate_suite_key_kind(key: bytes, kind: str) -> None:
    """Fail closed unless a suite label agrees with the key's disclosure status."""
    if not isinstance(key, bytes) or len(key) != 32:
        raise ValueError("suite key must be exactly 32 bytes")
    if kind not in ALLOWED_SUITE_KINDS:
        raise ValueError(f"suite kind must be one of {sorted(ALLOWED_SUITE_KINDS)!r}, not {kind!r}")
    scorecard_key = scorecard_measurement_key()
    if kind == DEV_SUITE_KIND and key != PUBLIC_DEV_KEY:
        raise ValueError("dev suite kind requires the published PUBLIC_DEV_KEY")
    if kind == SCORECARD_MEASUREMENT_KIND and key != scorecard_key:
        raise ValueError("scorecard-measurement suite kind requires its published measurement key")
    if kind == HOLDOUT_SUITE_KIND and key in {PUBLIC_DEV_KEY, scorecard_key}:
        raise ValueError("holdout suite kind cannot use a published reproducible key")


